// Phase 2 decision D4: reviews the Light + Muted directions for overlap. For every pair of them it lists
// the diversity measures they differ on, ΔEOK between grounds and between figures, and the domains they share.
// It changes nothing; the verdict in the output is curator judgement on these numbers.
// Output: research/data/analysis/light-muted-overlap.json and .md
import fs from 'node:fs';
import path from 'node:path';
import { RESEARCH } from './lib/sotd.mjs';
import { differences } from '../../tools/lib/diversity.mjs';
import { deltaEOK } from '../../tools/lib/color.mjs';

const lib = JSON.parse(fs.readFileSync(path.join(RESEARCH, '../library/directions.json'), 'utf8')).directions;
const lm = lib.filter((d) => d.classification.primary.display_label === 'Light + Muted');
const lch = (s) => [s.oklch.l, s.oklch.c, s.oklch.h];
const pairs = [];
for (let i = 0; i < lm.length; i++) for (let j = i + 1; j < lm.length; j++) {
  const a = lm[i], b = lm[j], ca = a.classification, cb = b.classification;
  pairs.push({
    a: a.name, b: b.name,
    differsOn: differences(ca, cb),
    groundDeltaEOK: +deltaEOK(lch(ca.ground), lch(cb.ground)).toFixed(3),
    figureDeltaEOK: +deltaEOK(lch(ca.figure), lch(cb.figure)).toFixed(3),
    sharedDomains: ca.industry.filter((x) => cb.industry.includes(x)),
  });
}
pairs.sort((x, y) => x.differsOn.length - y.differsOn.length || x.figureDeltaEOK - y.figureDeltaEOK);
const closest = pairs.filter((p) => p.differsOn.length <= 2 && p.sharedDomains.length);
fs.writeFileSync(path.join(RESEARCH, 'data/analysis/light-muted-overlap.json'), JSON.stringify({ directions: lm.map((d) => d.name), pairs, closest }, null, 1) + '\n');

const md = `# Light + Muted overlap review

Generated by \`research/tools/light-muted-overlap.mjs\` for Phase 2 decision D4. Nothing in the library was changed.

The ${lm.length} directions:

| Direction | Ground | Figure | Figure hue | Domains |
| --- | --- | --- | ---: | --- |
${lm.map((d) => { const c = d.classification; return `| ${d.name} | ${c.ground.name} ${c.ground.hex} | ${c.figure.name} ${c.figure.hex} | ${c.figure.oklch.h ?? '–'}° | ${c.industry.join(', ')} |`; }).join('\n')}

Every pair, closest first (fewest differing measures, then smallest figure ΔEOK):

| A | B | Differs on | Ground ΔEOK | Figure ΔEOK | Shared domains |
| --- | --- | --- | ---: | ---: | --- |
${pairs.map((p) => `| ${p.a} | ${p.b} | ${p.differsOn.join(', ')} (${p.differsOn.length}) | ${p.groundDeltaEOK} | ${p.figureDeltaEOK} | ${p.sharedDomains.join(', ') || '–'} |`).join('\n')}

Pairs that differ on two measures or fewer and also share a domain, so a query could show them together: ${closest.length ? closest.map((p) => `${p.a} and ${p.b} (${p.sharedDomains.join(', ')})`).join('; ') : 'none'}.

## Verdict (curator judgement)

${pairs.filter((p) => p.differsOn.length === 1).map((p) => `${p.a} and ${p.b}`).join(', ')} differ only in figure lightness: one hue on almost the same near-white ground, once as a mid-tone and once as a deep tone. Six of the ${lm.length} grounds are within ΔEOK 0.03 of each other, so the group is really one idea, a near-white ground with one muted figure, varied by hue and figure depth. Kraft and Black is the exception, with a tan ground.

No pair that is close also shares a domain, so no query shows two of them together, and the build's rule that library directions differ on at least one measure holds. **Keep all seven** (Phase 2 D4). For future curation, a new Light + Muted direction would add little unless it changes the ground; the pause in \`library/policy.json\` already stops the group from growing.
`;
fs.writeFileSync(path.join(RESEARCH, 'data/analysis/light-muted-overlap.md'), md);
console.log(md);
